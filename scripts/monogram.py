def seg(points):
    """Гладкий отрезок Catmull-Rom -> кубические Безье. Возвращает ' C…' команды (без начальной M)."""
    p = [points[0]] + list(points) + [points[-1]]
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}")
    return out

def path(*segments):
    """Замкнутый контур из гладких отрезков; на стыках отрезков — углы."""
    d = [f"M{segments[0][0][0]:.1f},{segments[0][0][1]:.1f}"]
    for k, s in enumerate(segments):
        if k and s[0] != segments[k - 1][-1]:
            d.append(f"L{s[0][0]:.1f},{s[0][1]:.1f}")
        d += seg(s) if len(s) > 2 else [f"L{s[-1][0]:.1f},{s[-1][1]:.1f}"]
    return " ".join(d) + "Z"

